"""Coverage denominator: spec sections (primary) + opcodes (roll-up).

`opcode` here is the coverage-index's own disambiguating id (admin and NVM
command sets reuse the same raw opcode numbers, e.g. 0x02 = Get Log Page on
Admin vs Read on NVM) — `raw_opcode` is the real value to send over the wire.

`SpecCoverageIndexFile` loads whichever index file is active (see
`config.active_coverage_index_path`): normally `specs/spec_coverage_index.json`
generated by `build_spec_index.py` from the real spec text, falling back to the
small hand-written seed when that has not been generated yet.
"""
from abc import ABC, abstractmethod

from shared.file_store import load_json


class SpecCoverageIndex(ABC):
    @abstractmethod
    def list_sections(self) -> list[dict]:
        ...

    @abstractmethod
    def list_opcodes(self) -> list[dict]:
        ...

    def get_opcode(self, opcode: str) -> dict | None:
        return next((o for o in self.list_opcodes() if o["opcode"] == opcode), None)

    def opcodes_for_section(self, section: dict) -> list[dict]:
        return [o for o in self.list_opcodes() if o["opcode"] in section.get("related_opcodes", [])]

    def get_opcode_by_name(self, name: str, command_set: str) -> dict | None:
        return next((o for o in self.list_opcodes()
                     if o["name"] == name and o["command_set"] == command_set), None)

    def get_section(self, section_id: str) -> dict | None:
        return next((s for s in self.list_sections() if s["section_id"] == section_id), None)


SUPPORTED_SCHEMA_VERSIONS = (1, 2, 3)


class SpecCoverageIndexFile(SpecCoverageIndex):
    def __init__(self, path):
        data = load_json(path)
        if data is None:
            raise FileNotFoundError(f"coverage index not found: {path}")
        version = data.get("schema_version", 1)
        if version not in SUPPORTED_SCHEMA_VERSIONS:
            raise ValueError(
                f"{path} has schema_version {version}; this loader understands "
                f"{SUPPORTED_SCHEMA_VERSIONS}. Re-run build_spec_index.py.")
        self.schema_version = version
        self.source = data.get("source", "unknown")
        self._sections = data["sections"]
        self._opcodes = data["opcodes"]

    def list_sections(self) -> list[dict]:
        return self._sections

    def list_opcodes(self) -> list[dict]:
        return self._opcodes
