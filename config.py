import json
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent

QST_DIR = BASE_DIR / "QST"
PULSEFZ_DIR = BASE_DIR / "PULSEFZ"

DATA_DIR = BASE_DIR / "data"
FAILURE_CONTEXTS_DIR = DATA_DIR / "failure_contexts"
VERDICTS_DIR = DATA_DIR / "verdicts"
TC_STORE_PATH = DATA_DIR / "tc_store.json"
COVERAGE_STATE_PATH = DATA_DIR / "coverage_state.json"
# Targets skipped before anything reached the device (generation/argument
# failure, destructive gate). Counted as attempts so target selection rotates.
TARGET_SKIPS_PATH = DATA_DIR / "target_skips.json"
INGEST_STATE_QST_PATH = DATA_DIR / "ingest_state_qst.json"
INGEST_STATE_PULSEFZ_PATH = DATA_DIR / "ingest_state_pulsefz.json"

SPECS_DIR = BASE_DIR / "specs"
SEED_COVERAGE_INDEX_PATH = SPECS_DIR / "seed_coverage_index.json"
# Generated by build_spec_index.py from the real RAG spec index; preferred over
# the hand-written seed when present.
SPEC_COVERAGE_INDEX_PATH = SPECS_DIR / "spec_coverage_index.json"


def active_coverage_index_path():
    return SPEC_COVERAGE_INDEX_PATH if SPEC_COVERAGE_INDEX_PATH.exists() else SEED_COVERAGE_INDEX_PATH

RAG_DIR = BASE_DIR / "rag"
RAG_INDEX_DIR = RAG_DIR / "index"
RAG_INDEX_CURRENT_PATH = RAG_INDEX_DIR / "current"

# Audit log, not reconstructible state (unlike DATA_DIR) — kept separate so
# log rotation/cleanup never risks touching pipeline state.
LOGS_DIR = BASE_DIR / "logs"
LLM_CALL_LOG_PATH = LOGS_DIR / "llm_calls.jsonl"
SSH_COMMAND_LOG_PATH = LOGS_DIR / "ssh_commands.jsonl"

REPORT_OUTPUT_DIR = BASE_DIR / "report" / "output"
REPORT_LATEST_PATH = REPORT_OUTPUT_DIR / "report_latest.html"

SECRETS_PATH = BASE_DIR / "secrets.local.json"

PULSEFZ_MAX_TAIL_SCAN_BYTES = 8 * 1024 * 1024
LOG_EXCERPT_CONTEXT_LINES = 40


def _load_secrets():
    if not SECRETS_PATH.exists():
        raise FileNotFoundError(
            f"{SECRETS_PATH} not found — copy secrets.local.example.json to "
            "secrets.local.json and fill in ssh_host/ssh_user/ssh_password."
        )
    return json.loads(SECRETS_PATH.read_text(encoding="utf-8"))


def get_ssh_target():
    secrets = _load_secrets()
    return {
        "host": secrets["ssh_host"],
        "user": secrets["ssh_user"],
        "password": secrets["ssh_password"],
        "nvme_ctrl": secrets.get("nvme_ctrl", "/dev/nvme0"),
        "nvme_ns": secrets.get("nvme_ns", "/dev/nvme0n1"),
    }


for _dir in (
    DATA_DIR,
    FAILURE_CONTEXTS_DIR / "qst",
    FAILURE_CONTEXTS_DIR / "pulsefz",
    FAILURE_CONTEXTS_DIR / "tc_exec",
    VERDICTS_DIR,
    SPECS_DIR,
    REPORT_OUTPUT_DIR,
    LOGS_DIR,
):
    _dir.mkdir(parents=True, exist_ok=True)
